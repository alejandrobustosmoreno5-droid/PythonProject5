#Le pedimos dos numeros
num1 = int(input("Introduce el primer número: "))
num2 = int(input("Introduce el segundo número: "))
#Si el primer numero es mayor que el segundo pondra "El primero es mayor"
#Si el segundo numero es mayor que el primer numero pondra"El primero no es mayor"
if num1 > num2:
    print("El primero es mayor")
else:
    print("El primero no es mayor")